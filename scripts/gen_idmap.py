#!/usr/bin/env python3
"""Generate CAN ID map artifacts from dbc/vecu.dbc (single source of truth).

Outputs (both carry a "GENERATED" header marker):
  include/id_map.h        CAN ID #defines + monitor track table {id,name,dlc}
  analysis/idmap_gen.py   ID<->name dicts, per-ID DLC and signal-name lists

Usage:
  python3 scripts/gen_idmap.py            # (re)generate both artifacts
  python3 scripts/gen_idmap.py --check    # byte-compare vs disk; exit 1 + diff
                                          # summary when stale (used by CI)

Deliberately cantools-free: plain-text parse of BO_/SG_ lines only.
"""
import argparse
import difflib
import os
import re
import sys

RE_BO = re.compile(r"^BO_\s+(\d+)\s+([A-Za-z_]\w*)\s*:\s*(\d+)\s+\S+")
# Full SG_ line: SG_ Name : start|len@order+ (factor,offset) [min|max] "unit" receivers
RE_SG = re.compile(
    r"^\s*SG_\s+([A-Za-z_]\w*)\s*:\s*"
    r"(\d+)\|(\d+)@([01])([+-])\s*"
    r"\(([\d.+-]+),([\d.+-]+)\)\s*"
    r"\[([\d.+-]+)\|([\d.+-]+)\]\s*"
    r'"([^"]*)"\s*'
    r"(.+)$"
)

MARKER = ("GENERATED by scripts/gen_idmap.py from dbc/vecu.dbc - "
          "edit gen source, not this file")


def parse_dbc(path):
    """Parse BO_ messages (id, name, dlc) and their SG_ signals with full metadata."""
    msgs = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = RE_BO.match(line)
            if m:
                msgs.append({"id": int(m.group(1)), "name": m.group(2),
                             "dlc": int(m.group(3)), "signals": []})
                continue
            m = RE_SG.match(line)
            if m and msgs:
                sig = {
                    "name": m.group(1),
                    "start_bit": int(m.group(2)),
                    "length": int(m.group(3)),
                    "byte_order": int(m.group(4)),  # 0=big-endian(Motorola), 1=little-endian(Intel)
                    "is_signed": m.group(5) == "-",
                    "factor": float(m.group(6)),
                    "offset": float(m.group(7)),
                    "min_val": float(m.group(8)),
                    "max_val": float(m.group(9)),
                    "unit": m.group(10),
                    "receivers": [r.strip() for r in m.group(11).split(",")],
                }
                msgs[-1]["signals"].append(sig)
    msgs.sort(key=lambda x: x["id"])
    return msgs


def build_header(msgs):
    """include/id_map.h: CAN ID #defines + monitor track table (struct of
    {canid_t id; const char *name; uint8_t dlc}). Self-contained header: it
    must not include common.h (common.h includes this file)."""
    out = []
    out.append("/* vECU-Bench CAN ID map.")
    out.append(" * %s." % MARKER)
    out.append(" * Regenerate: python3 scripts/gen_idmap.py")
    out.append(" * Verify:     python3 scripts/gen_idmap.py --check (CI enforces)")
    out.append(" * SPDX-License-Identifier: MIT")
    out.append(" */")
    out.append("#ifndef VECU_ID_MAP_H")
    out.append("#define VECU_ID_MAP_H")
    out.append("")
    out.append("#include <linux/can.h>   /* canid_t; intentionally no common.h (cycle) */")
    out.append("")
    out.append("/* ---- CAN IDs (from dbc/vecu.dbc, ascending) ---- */")
    for m in msgs:
        sigs = ",".join(s["name"] for s in m["signals"]) or "-"
        out.append("#define CAN_ID_%-16s 0x%03Xu  /* %-14s dlc=%d  %s */"
                   % (m["name"], m["id"], m["name"], m["dlc"], sigs))
    out.append("")
    out.append("/* ---- monitor track table: every DBC message ---- */")
    out.append("#define VECU_ID_MAP_TRACK_COUNT %d" % len(msgs))
    out.append("")
    out.append("struct vecu_id_map_entry {")
    out.append("    canid_t     id;")
    out.append("    const char *name;")
    out.append("    uint8_t     dlc;")
    out.append("};")
    out.append("")
    out.append("static const struct vecu_id_map_entry VECU_ID_MAP_TRACK[%d] = {"
               % len(msgs))
    for m in msgs:
        out.append('    { 0x%03Xu, "%s", %du },' % (m["id"], m["name"], m["dlc"]))
    out.append("};")
    out.append("")
    out.append("#endif /* VECU_ID_MAP_H */")
    return "\n".join(out) + "\n"


def build_idmap_py(msgs):
    """analysis/idmap_gen.py: importable ID<->name / dlc / signal dicts."""
    out = []
    out.append("#!/usr/bin/env python3")
    out.append('"""CAN ID map.')
    out.append(MARKER[0].upper() + MARKER[1:] + ".")
    out.append("Regenerate: python3 scripts/gen_idmap.py")
    out.append('"""')
    out.append("")
    out.append("ID_TO_NAME = {")
    for m in msgs:
        out.append('    0x%03X: "%s",' % (m["id"], m["name"]))
    out.append("}")
    out.append("")
    out.append("NAME_TO_ID = {")
    for m in msgs:
        out.append('    "%s": 0x%03X,' % (m["name"], m["id"]))
    out.append("}")
    out.append("")
    out.append("ID_TO_DLC = {")
    for m in msgs:
        out.append("    0x%03X: %d," % (m["id"], m["dlc"]))
    out.append("}")
    out.append("")
    out.append("ID_TO_SIGNALS = {")
    for m in msgs:
        sigs = ", ".join('"%s"' % s["name"] for s in m["signals"])
        if len(m["signals"]) == 1:
            sigs += ","   # keep a 1-tuple a tuple
        out.append("    0x%03X: (%s)," % (m["id"], sigs))
    out.append("}")
    out.append("")
    out.append("ID_TO_SIGNAL_INFO = {")
    for m in msgs:
        out.append("    0x%03X: {" % m["id"])
        for sig in m["signals"]:
            out.append('        "%s": {' % sig["name"])
            out.append('            "start_bit": %d,' % sig["start_bit"])
            out.append('            "length": %d,' % sig["length"])
            out.append('            "byte_order": %d,' % sig["byte_order"])
            out.append('            "is_signed": %s,' % ("True" if sig["is_signed"] else "False"))
            out.append('            "factor": %s,' % sig["factor"])
            out.append('            "offset": %s,' % sig["offset"])
            out.append('            "min": %s,' % sig["min_val"])
            out.append('            "max": %s,' % sig["max_val"])
            out.append('            "unit": "%s",' % sig["unit"])
            out.append('            "receivers": %s,' % sig["receivers"])
            out.append("        },")
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def write_lf(path, content):
    """Write with forced LF newlines so --check is byte-stable across OSes."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


def check_file(path, expected, diffs):
    """Byte-compare expected content vs on-disk file; record diff summary."""
    if not os.path.exists(path):
        diffs.append("%s: MISSING (run: python3 scripts/gen_idmap.py)" % path)
        return False
    with open(path, "rb") as f:
        actual = f.read()
    exp_b = expected.encode("utf-8")
    if actual == exp_b:
        print("ok      %s" % path)
        return True
    d = list(difflib.unified_diff(
        actual.decode("utf-8", "replace").splitlines(),
        exp_b.decode("utf-8").splitlines(),
        fromfile="%s (on disk)",
        tofile="%s (regenerated)" % path,
        lineterm=""))
    diffs.append("%s: STALE (%d diff lines, first 20 shown)" % (path, len(d)))
    diffs.extend("    " + x for x in d[:20])
    return False


# Key signals that must have correct scaling validation
# Keys must match the signal dict keys from parse_dbc
KEY_SIGNALS = {
    "SpeedKphX10": {"factor": 0.1, "offset": 0, "min_val": 0, "max_val": 6553.5, "unit": "km/h"},
    "DistCm": {"factor": 1, "offset": 0, "min_val": 0, "max_val": 65535, "unit": "cm"},
    "TempCelsiusX10": {"factor": 0.1, "offset": 0, "min_val": 0, "max_val": 6553.5, "unit": "degC"},
    "BrakeLevel": {"factor": 1, "offset": 0, "min_val": 0, "max_val": 100, "unit": "%"},
    "LightState": {"factor": 1, "offset": 0, "min_val": 0, "max_val": 2, "unit": ""},
}


def validate_signal_scaling(msgs, diffs):
    """Validate that key signals have correct scaling/offset/min/max/unit per DBC."""
    ok = True
    for m in msgs:
        for sig in m["signals"]:
            if sig["name"] in KEY_SIGNALS:
                expected = KEY_SIGNALS[sig["name"]]
                for field, exp_val in expected.items():
                    actual_val = sig.get(field)
                    if actual_val is None:
                        diffs.append(
                            "SIGNAL SCALING MISSING: %s (ID 0x%03X).%s has no field '%s'"
                            % (m["name"], m["id"], sig["name"], field)
                        )
                        ok = False
                        continue
                    if field == "unit":
                        if actual_val != exp_val:
                            diffs.append(
                                "SIGNAL SCALING MISMATCH: %s (ID 0x%03X).%s unit: "
                                "expected '%s', got '%s'"
                                % (m["name"], m["id"], sig["name"], exp_val, actual_val)
                            )
                            ok = False
                    else:
                        # Allow small floating point tolerance
                        if abs(actual_val - exp_val) > 1e-9:
                            diffs.append(
                                "SIGNAL SCALING MISMATCH: %s (ID 0x%03X).%s %s: "
                                "expected %s, got %s"
                                % (m["name"], m["id"], sig["name"], field, exp_val, actual_val)
                            )
                            ok = False
    if ok:
        print("ok      signal scaling validation (key signals)")
    return ok


def main():
    ap = argparse.ArgumentParser(
        description="Generate CAN ID map artifacts from dbc/vecu.dbc")
    ap.add_argument("--check", action="store_true",
                    help="verify artifacts match DBC; exit 1 + diff if stale")
    ap.add_argument("--dbc", default="dbc/vecu.dbc")
    ap.add_argument("--header", default="include/id_map.h")
    ap.add_argument("--idmap-py", default="analysis/idmap_gen.py")
    args = ap.parse_args()

    # Resolve relative paths against the repo root (dir above scripts/),
    # so the tool works from any cwd.
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

    def abspath(p):
        return p if os.path.isabs(p) else os.path.join(root, p)

    dbc, header, pymod = (abspath(args.dbc), abspath(args.header),
                          abspath(args.idmap_py))
    if not os.path.exists(dbc):
        print("error: DBC not found: %s" % dbc, file=sys.stderr)
        return 1
    msgs = parse_dbc(dbc)
    if not msgs:
        print("error: no BO_ messages parsed from %s" % dbc, file=sys.stderr)
        return 1

    h_content, py_content = build_header(msgs), build_idmap_py(msgs)

    if args.check:
        diffs = []
        ok = check_file(header, h_content, diffs)
        ok = check_file(pymod, py_content, diffs) and ok
        ok = validate_signal_scaling(msgs, diffs) and ok
        if ok:
            print("ID map artifacts up to date (%d messages)" % len(msgs))
            return 0
        for line in diffs:
            print(line, file=sys.stderr)
        print("stale artifacts - run: python3 scripts/gen_idmap.py",
              file=sys.stderr)
        return 1

    write_lf(header, h_content)
    write_lf(pymod, py_content)
    print("generated %s and %s (%d messages)"
          % (os.path.relpath(header, root), os.path.relpath(pymod, root),
             len(msgs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
