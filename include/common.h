/* Nominal bitrate used for bus-load calculations. vcan does not simulate
 * bit timing, so this is the reference value the testbed is modeled for. */
#define VECU_BITRATE_KBIT    500

/* ---- measured-frame payload layout (little endian, classic CAN, dlc=8) ----
 * [0..1] seq    u16  per-ID sequence counter (loss detection)
 * [2..5] tx_ms  u32  CLOCK_MONOTONIC ms truncated to 32 bit (one-way latency)
 * [6..7] value  u16  application signal (scaled per DBC)
 * CMD_BRAKE value = (src_seq8 << 8) | brake_level  -> enables end-to-end
 * correlation (sensor seq -> brake command) in analysis.
 */
static inline uint64_t now_ms(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (uint64_t)ts.tv_sec * 1000ull + (uint64_t)ts.tv_nsec / 1000000ull;
}

static inline uint64_t now_us(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (uint64_t)ts.tv_sec * 1000000ull + (uint64_t)ts.tv_nsec / 1000ull;
}

/* nominal on-wire bits of a CAN 2.0A data frame: 47 + 8*dlc (worst-case bit
 * stuffing adds up to floor((34 + 8*dlc - 1)/4); we report nominal and mark
 * worst-case separately). */
static inline double frame_bits_nominal(int dlc) { return 47.0 + 8.0 * dlc; }
static inline double frame_bits_worst(int dlc)
{
    return frame_bits_nominal(dlc) + (double)((34 + 8 * dlc - 1) / 4);
}

