/* ---- cooperative periodic task scheduler (sched.c) ---- */
typedef struct node node_t;
typedef void (*task_fn)(node_t *);
typedef void (*rx_fn)(node_t *, const struct can_frame *);

struct task {
    const char *name;
    uint32_t    period_ms;
    task_fn     fn;
    uint64_t    next_ms;
    uint64_t    runs;
    uint64_t    jitter_max_us;   /* worst |start - deadline| observed */
};

#define NODE_MAX_TASKS 8

struct node {
    int          fd;
    const char  *name;
    uint8_t      node_id;
    struct task  tasks[NODE_MAX_TASKS];
    int          ntasks;
    rx_fn        on_rx;
    void        *state;          /* application state */
    uint64_t     rx_errors;      /* receive errors */
};

extern volatile sig_atomic_t g_running;
void install_signal_handlers(void);
int  node_add_task(node_t *n, const char *name, uint32_t period_ms, task_fn fn);
int  node_run(node_t *n, uint32_t duration_s);   /* 0 = run until signal */
void node_print_stats(const node_t *n);

/* ---- saturating increment for uint64_t counters (prevents overflow) ---- */
static inline void SATURATING_INC(uint64_t *ptr)
{
    if (*ptr < UINT64_MAX)
        (*ptr)++;
}

